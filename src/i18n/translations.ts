export type TranslationKey = keyof typeof TRANSLATIONS.en;

let activeLang: Language = 'en';

export const setActiveLanguage = (lang: Language) => {
  activeLang = lang;
};

export const getActiveLanguage = (): Language => activeLang;

export const translate = (
  lang: Language,
  key: TranslationKey,
  params?: Record<string, string | number>
): string => {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text: string = (dictionary as any)[key] || TRANSLATIONS.en[key] || key;

  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    }
  }

  return text;
};

export const t = (
  key: TranslationKey,
  params?: Record<string, string | number>
): string => {
  return translate(activeLang, key, params);
};
